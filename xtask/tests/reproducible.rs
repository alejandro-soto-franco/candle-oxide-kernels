//! Guards against a committed artifact drifting from the source that
//! generates it. Regenerates both families into a scratch directory and
//! diffs the result against `candle-oxide-kernels/ptx/`.
//!
//! This only proves anything because generation is deterministic: two runs
//! produce byte-identical output (verified by hand while writing this test,
//! `sha256sum` matching across two separate `--out` directories and against
//! the committed files). If a future change to the codegen makes output
//! depend on wall-clock time, an absolute path, or hash-ordered iteration,
//! this test starts failing intermittently rather than on genuine drift.
//! Treat that as a codegen bug to fix; the comparison here stays exact.

use std::process::Command;

/// Compare `got` against the committed `want` for `name`, panicking with a
/// compact report rather than `assert_eq!`'s full-string dump.
///
/// A real drift between two PTX files that are each tens of kilobytes
/// floods the log if the whole `left`/`right` pair is printed, and the
/// actionable line lands after it. This reports the artifact name, both
/// byte lengths, and a few lines of context around the first difference
/// instead.
fn assert_matches_committed(name: &str, want: &str, got: &str) {
    if got == want {
        return;
    }

    let want_lines: Vec<&str> = want.lines().collect();
    let got_lines: Vec<&str> = got.lines().collect();
    let first_diff = want_lines
        .iter()
        .zip(got_lines.iter())
        .position(|(w, g)| w != g)
        .unwrap_or_else(|| want_lines.len().min(got_lines.len()));

    let context = |lines: &[&str], at: usize| -> String {
        let start = at.saturating_sub(1);
        let end = (at + 2).min(lines.len());
        lines[start..end]
            .iter()
            .enumerate()
            .map(|(offset, line)| format!("    {}: {line}", start + offset + 1))
            .collect::<Vec<_>>()
            .join("\n")
    };

    panic!(
        "{name} drifted from its source ({} committed bytes, {} regenerated bytes). \
         First difference at line {}.\n  committed:\n{}\n  regenerated:\n{}\n\
         Run `cargo xtask gen-ptx` and commit the result.",
        want.len(),
        got.len(),
        first_diff + 1,
        context(&want_lines, first_diff),
        context(&got_lines, first_diff),
    );
}

#[test]
fn regenerating_reproduces_the_committed_artifacts() {
    let root = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("..");
    let committed = root.join("candle-oxide-kernels/ptx");
    let unique = std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .map(|d| d.as_nanos())
        .unwrap_or(0);
    let fresh = std::env::temp_dir().join(format!("xtask_repro_{}_{}", std::process::id(), unique));

    let out = Command::new(env!("CARGO_BIN_EXE_xtask"))
        .args(["gen-ptx", "--arch", "sm_80", "--out"])
        .arg(&fresh)
        .output()
        .expect("xtask runs");
    assert!(
        out.status.success(),
        "generation failed:\n{}",
        String::from_utf8_lossy(&out.stderr)
    );

    for name in ["binary.ptx", "unary.ptx"] {
        let want = std::fs::read_to_string(committed.join(name)).unwrap();
        let got = std::fs::read_to_string(fresh.join(name)).unwrap();
        assert_matches_committed(name, &want, &got);
    }
    let _ = std::fs::remove_dir_all(&fresh);
}
